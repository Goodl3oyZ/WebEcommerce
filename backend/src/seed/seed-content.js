async function seedContent() {
  let added = 0;
  for (const post of STARTER) {
    const exists = await db.query.posts.findFirst({ where: eq(posts.slug, post.slug), columns: { id: true } });
    if (exists) continue;
    await db.insert(posts).values({ ...post, status: "published", publishedAt: new Date() });
    added += 1;
  }
  console.log(`Starter content: added ${added}, kept ${STARTER.length - added} existing`);
}

seedContent()
  .then(() => process.exit(0))
  .catch((error) => {
    console.error("Content seed failed:", error);
    process.exit(1);
  });
